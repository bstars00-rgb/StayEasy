export const translations = { en, ko, vi, zh, ja }

function resolve(obj, path) {
  return path.split('.').reduce((acc, k) => (acc == null ? undefined : acc[k]), obj)
}

function interpolate(str, vars) {
  if (typeof str !== 'string' || !vars) return str
  return str.replace(/\{(\w+)\}/g, (_, name) => (vars[name] != null ? String(vars[name]) : `{${name}}`))
}

/**
 * Resolve a dot-path key for `lang`, falling back to English, then to the
 * raw key string. Pure function — safe to import anywhere (no React deps).
 */
export function translate(lang, key, vars) {
  const primary = resolve(translations[lang], key)
  if (primary != null) return interpolate(primary, vars)
  const fallback = resolve(translations[DEFAULT_LANG], key)
  if (fallback != null) return interpolate(fallback, vars)
  return key
}
